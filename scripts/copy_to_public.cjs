// copy_to_public.cjs
// Copies generated storefront files into the public directory for Vercel deployment.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PUBLIC = path.join(ROOT, 'public');
if (!fs.existsSync(PUBLIC)) fs.mkdirSync(PUBLIC, { recursive: true });

// Helper to copy a file if it exists
function copyFile(src) {
  if (fs.existsSync(src)) {
    const dest = path.join(PUBLIC, path.basename(src));
    fs.copyFileSync(src, dest);
    console.log(`Copied ${src} → ${dest}`);
  }
}
// Helper to copy a directory recursively
function copyDir(srcDir) {
  if (!fs.existsSync(srcDir)) return;
  const entries = fs.readdirSync(srcDir, { withFileTypes: true });
  for (const entry of entries) {
    const srcPath = path.join(srcDir, entry.name);
    const destPath = path.join(PUBLIC, entry.name);
    if (entry.isDirectory()) {
      if (!fs.existsSync(destPath)) fs.mkdirSync(destPath, { recursive: true });
      copyDir(srcPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

// Files generated by scripts/generate_all_pages.cjs and other scripts
const generatedFiles = [
  path.join(ROOT, 'sitemap.xml'),
  path.join(ROOT, 'robots.txt'),
  path.join(ROOT, 'assets', 'catalog.json')
];
generatedFiles.forEach(copyFile);

// Copy all HTML product pages (assumed to be in root)
fs.readdirSync(ROOT).forEach(file => {
  if (file.endsWith('.html')) {
    copyFile(path.join(ROOT, file));
  }
});

// Copy assets directory (images, css, js, etc.)
copyDir(path.join(ROOT, 'assets'));

// Copy products directory containing any additional resources
copyDir(path.join(ROOT, 'products'));

console.log('Public directory prepared.');
